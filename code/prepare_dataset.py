"""Copy the selected instructor images into a YOLO folder layout.

Reads dataset/selection_manifest.csv and copies each picked image from the
raw download folder into dataset/images/{train,val}/, renamed with its fire
event id as a prefix (E07_1644862570_+02040.jpg) so that files from the same
sequence sort together while labeling. Also writes dataset/data.yaml with
absolute paths and creates the empty labels/ folders.

Usage (from the repo root):
    python code/prepare_dataset.py --raw ~/Downloads/training

If dataset/images/ holds images that are no longer in the manifest (for
example after the selection was trimmed), the script lists them. Add
--move-extra to move them, and any label files they have, into
dataset/unused/ instead of deleting them.

The raw images are never modified. Nothing is deleted.
"""
import argparse
import csv
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATASET = REPO / "dataset"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", required=True, help="folder with the instructor's raw .jpg files")
    ap.add_argument("--out", default=str(DATASET), help="dataset root (default: dataset/)")
    ap.add_argument("--move-extra", action="store_true",
                    help="move images/labels not in the manifest into <out>/unused/")
    args = ap.parse_args()

    raw = Path(args.raw).expanduser().resolve()
    out = Path(args.out).expanduser().resolve()
    rows = list(csv.DictReader(open(DATASET / "selection_manifest.csv", newline="")))

    missing = []
    copied = 0
    for split in ("train", "val"):
        (out / "images" / split).mkdir(parents=True, exist_ok=True)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)
    for r in rows:
        src = raw / r["source_file"]
        dst = out / "images" / r["split"] / r["dataset_file"]
        if not src.exists():
            missing.append(r["source_file"])
            continue
        if not dst.exists():
            shutil.copy2(src, dst)
            copied += 1

    wanted = {(r["split"], r["dataset_file"]) for r in rows}
    extra = sorted(p for split in ("train", "val") for p in (out / "images" / split).glob("*")
                   if p.is_file() and (split, p.name) not in wanted)
    moved = 0
    for img in extra:
        split = img.parent.name
        if args.move_extra:
            for src, kind in ((img, "images"), (out / "labels" / split / (img.stem + ".txt"), "labels")):
                if src.exists():
                    dst = out / "unused" / kind / split / src.name
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.move(str(src), str(dst))
            moved += 1

    (out / "data.yaml").write_text(
        "# Generated by code/prepare_dataset.py\n"
        f"path: {out}\n"
        "train: images/train\n"
        "val: images/val\n"
        "names:\n"
        "  0: smoke\n"
    )
    print(f"{len(rows)} images in manifest, {copied} newly copied, {len(missing)} missing")
    if extra and args.move_extra:
        print(f"Moved {moved} images that are no longer selected (and their labels) into {out / 'unused'}")
    elif extra:
        print(f"{len(extra)} images in {out / 'images'} are no longer in the manifest. "
              "Re-run with --move-extra to move them into dataset/unused/.")
    if missing:
        print("Missing from --raw folder:", *missing[:20], sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
