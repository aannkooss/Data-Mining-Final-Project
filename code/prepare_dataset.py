"""Copy the selected instructor images into a YOLO folder layout.

Reads dataset/selection_manifest.csv and copies each picked image from the
raw download folder into dataset/images/{train,val}/, renamed with its fire
event id as a prefix (E07_1644862570_+02040.jpg) so that files from the same
sequence sort together while labeling. Also writes dataset/data.yaml with
absolute paths and creates the empty labels/ folders.

Usage (from the repo root):
    python code/prepare_dataset.py --raw ~/Downloads/training

The raw images are never modified. Nothing is deleted.
"""
import argparse
import csv
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATASET = REPO / "dataset"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", required=True, help="folder with the instructor's raw .jpg files")
    ap.add_argument("--out", default=str(DATASET), help="dataset root (default: dataset/)")
    args = ap.parse_args()

    raw = Path(args.raw).expanduser().resolve()
    out = Path(args.out).expanduser().resolve()
    rows = list(csv.DictReader(open(DATASET / "selection_manifest.csv", newline="")))

    missing = []
    copied = 0
    for split in ("train", "val"):
        (out / "images" / split).mkdir(parents=True, exist_ok=True)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)
    for r in rows:
        src = raw / r["source_file"]
        dst = out / "images" / r["split"] / r["dataset_file"]
        if not src.exists():
            missing.append(r["source_file"])
            continue
        if not dst.exists():
            shutil.copy2(src, dst)
            copied += 1

    (out / "data.yaml").write_text(
        "# Generated by code/prepare_dataset.py\n"
        f"path: {out}\n"
        "train: images/train\n"
        "val: images/val\n"
        "names:\n"
        "  0: smoke\n"
    )
    print(f"{len(rows)} images in manifest, {copied} newly copied, {len(missing)} missing")
    if missing:
        print("Missing from --raw folder:", *missing[:20], sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
